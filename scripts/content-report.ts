// Prints content counts and validation results, and writes docs/curriculum-mapping-report.md.
// Run: npm run content:report
import { writeFileSync } from 'node:fs';
import { MISSIONS } from '../src/content';
import { CATEGORY_BY_ID } from '../src/content/categories';
import { CURRICULA } from '../src/content/curricula';
import { STORIES, STORY_LENGTH_GUIDE, wordCount } from '../src/content/stories';
import { validateMissions } from '../src/content/validate';

const report = validateMissions(MISSIONS);
const questions = MISSIONS.flatMap((m) => m.questions);
const byType: Record<string, number> = {};
for (const q of questions) byType[q.activityType] = (byType[q.activityType] ?? 0) + 1;
const verified = questions.filter((q) => q.curriculum.mappingStatus === 'verified').length;

console.log(`Missions: ${MISSIONS.length}  Questions: ${questions.length}`);
console.log('By activity type:', byType);
console.log(`Mappings verified: ${verified}  pending teacher review: ${questions.length - verified}`);
console.log(`Errors: ${report.errors.length}  Warnings: ${report.warnings.length}`);
report.errors.forEach((e) => console.log('  ERROR', e));
report.warnings.forEach((w) => console.log('  WARN', w));

const lines: string[] = [];
lines.push('# Curriculum Mapping Report', '');
lines.push('_Generated by `npm run content:report`. Do not edit by hand._', '');
lines.push('## Summary', '');
lines.push(`- Missions: **${MISSIONS.length}** · Questions: **${questions.length}**`);
lines.push(`- Verified mappings: **${verified}** · Pending teacher review: **${questions.length - verified}**`);
lines.push('- Standard codes entered: **0**. No codes, quotations or CEFR targets have been invented.');
lines.push('- Status of every item: **Pending teacher review**. The content must not be described as curriculum-aligned until reviewed.', '');
lines.push('## Source verification', '');
lines.push('The official reference pages on www.moe.gov.my could not be reached from the build environment (DNS/network allow-list), so neither the applicable curriculum version nor its implementation year was verified. A reviewer must confirm:', '');
for (const c of CURRICULA) {
  lines.push(`### ${c.name}`, '', c.description, '');
  for (const r of c.sourceReferences) lines.push(`- ${r.title}${r.url ? ` — <${r.url}>` : ''}: ${r.note}`);
  lines.push('');
}
lines.push('## What a reviewer needs to do', '');
lines.push('1. Confirm which document and edition apply to each school year.');
lines.push('2. For each mission below, confirm or correct the skill and learning objective, and enter the verified standard code in the mission spec (`src/content/missions/*.ts`, `buildMission` → curriculum).');
lines.push('3. Set `mappingStatus: \'verified\'`, `curriculumSource` and `standardCode` only after checking. The validator rejects codes on unverified items and verified items without a source.', '');
lines.push('## Missions (all pending teacher review)', '');
lines.push('| Mission id | Place | Year | Title | Skill | Proposed learning objective | Formats | Standard code | Status |');
lines.push('|---|---|---|---|---|---|---|---|---|');
for (const m of MISSIONS) {
  const formats = [...new Set(m.questions.map((q) => q.activityType))].join(', ');
  lines.push(`| ${m.id} | ${CATEGORY_BY_ID[m.categoryId].place} | ${m.yearLevel} | ${m.title} | ${m.curriculum.skill} | ${m.curriculum.learningObjective} | ${formats} | ${m.curriculum.standardCode ?? '— needs verification'} | ${m.curriculum.mappingStatus === 'verified' ? 'Verified' : 'Pending teacher review'} |`);
}
lines.push('', '## Story lengths (editorial guide, not a KPM requirement)', '');
for (const s of STORIES) {
  const [min, max] = STORY_LENGTH_GUIDE[s.yearLevel];
  lines.push(`- Year ${s.yearLevel} · ${s.title}: ${wordCount(s.text)} words (guide ${min}–${max})`);
}
lines.push('', '## Activity formats', '');
for (const [t, n] of Object.entries(byType)) lines.push(`- ${t}: ${n}`);
writeFileSync(new URL('../docs/curriculum-mapping-report.md', import.meta.url), lines.join('\n') + '\n');
console.log('Wrote docs/curriculum-mapping-report.md');
if (report.errors.length) process.exit(1);
